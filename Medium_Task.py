import soundfile as sf

def wav_to_logmel(
    file_path,
    sr=22050,
    duration=30.0,
    n_fft=2048,
    hop_length=512,
    n_mels=128,
    fmin=20,
    fmax=8000,
    target_frames=256
):
    try:
        y, sr = librosa.load(file_path, sr=sr, duration=duration, mono=True)
    except Exception:
        # fallback to soundfile
        try:
            y, sr_native = sf.read(file_path, always_2d=False)
            if y.ndim > 1:
                y = np.mean(y, axis=1)  # stereo -> mono
            # resample if needed
            if sr_native != sr:
                y = librosa.resample(y.astype(np.float32), orig_sr=sr_native, target_sr=sr)
        except Exception as e:
            # cannot decode this file
            return None

    # pad/cut to fixed duration
    target_len = int(sr * duration)
    if len(y) < target_len:
        y = np.pad(y, (0, target_len - len(y)))
    else:
        y = y[:target_len]

    mel = librosa.feature.melspectrogram(
        y=y, sr=sr, n_fft=n_fft, hop_length=hop_length,
        n_mels=n_mels, fmin=fmin, fmax=fmax, power=2.0
    )
    logmel = librosa.power_to_db(mel, ref=np.max)

    logmel = (logmel - logmel.mean()) / (logmel.std() + 1e-8)

    T = logmel.shape[1]
    if T < target_frames:
        logmel = np.pad(logmel, ((0,0),(0,target_frames - T)))
    else:
        logmel = logmel[:, :target_frames]

    return logmel.astype(np.float32)[None, :, :]

