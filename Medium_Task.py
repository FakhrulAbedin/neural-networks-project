def dbscan_summary(Z_use, eps, min_samples):
    pred = DBSCAN(eps=eps, min_samples=min_samples).fit_predict(Z_use)
    uniq, counts = np.unique(pred, return_counts=True)
    noise = counts[uniq == -1][0] if -1 in uniq else 0
    n_clusters = len(uniq) - (1 if -1 in uniq else 0)
    return pred, n_clusters, noise, len(pred)

