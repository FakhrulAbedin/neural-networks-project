class ConvVAE(nn.Module):
    def __init__(self, latent_dim=16):
        super().__init__()
        self.latent_dim = latent_dim

        # Input: (B, 1, 128, 256)
        self.enc = nn.Sequential(
            nn.Conv2d(1, 32, 4, 2, 1),   # (B, 32, 64, 128)
            nn.ReLU(),
            nn.Conv2d(32, 64, 4, 2, 1),  # (B, 64, 32, 64)
            nn.ReLU(),
            nn.Conv2d(64, 128, 4, 2, 1), # (B, 128, 16, 32)
            nn.ReLU(),
            nn.Conv2d(128, 256, 4, 2, 1) # (B, 256, 8, 16)
        )

        self.flatten_dim = 256 * 8 * 16
        self.fc_mu = nn.Linear(self.flatten_dim, latent_dim)
        self.fc_logvar = nn.Linear(self.flatten_dim, latent_dim)

        self.fc_dec = nn.Linear(latent_dim, self.flatten_dim)

        self.dec = nn.Sequential(
            nn.ConvTranspose2d(256, 128, 4, 2, 1), # (B, 128, 16, 32)
            nn.ReLU(),
            nn.ConvTranspose2d(128, 64, 4, 2, 1),  # (B, 64, 32, 64)
            nn.ReLU(),
            nn.ConvTranspose2d(64, 32, 4, 2, 1),   # (B, 32, 64, 128)
            nn.ReLU(),
            nn.ConvTranspose2d(32, 1, 4, 2, 1)     # (B, 1, 128, 256)
        )

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def forward(self, x):
        h = self.enc(x)
        h = h.view(x.size(0), -1)
        mu = self.fc_mu(h)
        logvar = self.fc_logvar(h)
        z = self.reparameterize(mu, logvar)

        h2 = self.fc_dec(z).view(x.size(0), 256, 8, 16)
        x_hat = self.dec(h2)
        return x_hat, mu, logvar, z

def vae_loss(x, x_hat, mu, logvar, beta=1.0):
    # reconstruction loss
    recon = F.mse_loss(x_hat, x, reduction="sum") / x.size(0)
    # KL divergence
    kl = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) / x.size(0)
    return recon + beta * kl, recon, kl

