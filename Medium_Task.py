class GTZANLogMelDataset(Dataset):
    def __init__(self, root_dir):
        self.items = []
        bad = 0

        for g in genres:
            gpath = os.path.join(root_dir, g)
            for f in os.listdir(gpath):
                if f.endswith(".wav"):
                    full = os.path.join(gpath, f)
                    x = wav_to_logmel(full)
                    if x is None:
                        bad += 1
                        continue
                    self.items.append((full, genre_to_id[g]))

        print(f"[Dataset] Loaded {len(self.items)} usable files. Skipped {bad} bad files.")

    def __len__(self):
        return len(self.items)

    def __getitem__(self, idx):
        path, y = self.items[idx]
        x = wav_to_logmel(path)
        # x should never be None now, but keep safe
        if x is None:
            x = np.zeros((1, 128, 256), dtype=np.float32)
        return torch.from_numpy(x), y, path

