def safe_metrics(Z_use, pred, true_labels=None, name="method"):
    uniq = np.unique(pred)
    if len(uniq) < 2:
        print(f"\n{name}: Not enough clusters for metrics (unique={uniq})")
        return

    # if DBSCAN has noise, remove noise for silhouette/CH/DB
    mask = np.ones(len(pred), dtype=bool)
    if -1 in uniq:
        mask = pred != -1
        if mask.sum() < 10 or len(np.unique(pred[mask])) < 2:
            print(f"\n{name}: DBSCAN produced too much noise for metrics.")
            return

    Zm = Z_use[mask]
    pm = pred[mask]

    sil = silhouette_score(Zm, pm)
    ch  = calinski_harabasz_score(Zm, pm)
    db  = davies_bouldin_score(Zm, pm)

    print(f"\n{name}")
    print("Silhouette:", sil)
    print("Calinski-Harabasz:", ch)
    print("Davies-Bouldin (lower better):", db)

    if true_labels is not None:
        ari = adjusted_rand_score(true_labels[mask], pm)
        print("ARI (using genre labels only for evaluation):", ari)

