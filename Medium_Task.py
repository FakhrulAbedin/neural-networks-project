from sklearn.metrics import silhouette_score, calinski_harabasz_score, davies_bouldin_score, adjusted_rand_score

def dbscan_metrics(Z_use, pred, true_labels=None):
    mask = pred != -1
    if mask.sum() < 10 or len(np.unique(pred[mask])) < 2:
        return None

    Zm = Z_use[mask]
    pm = pred[mask]

    sil = silhouette_score(Zm, pm)
    ch  = calinski_harabasz_score(Zm, pm)
    db  = davies_bouldin_score(Zm, pm)

    out = {
        "sil": sil,
        "ch": ch,
        "db": db,
        "clusters": len(np.unique(pm)),
        "kept": mask.sum()
    }

    if true_labels is not None:
        out["ari"] = adjusted_rand_score(true_labels[mask], pm)

    return out

